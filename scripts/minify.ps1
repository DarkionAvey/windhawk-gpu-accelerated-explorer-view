# Generated exports are outputs only; numbered sources remain authoritative.
function ConvertTo-MinifiedMod([string]$SourcePath) {
    if (!('WindhawkSourceMinifier' -as [type])) {
        Add-Type -Path (Join-Path $PSScriptRoot 'SourceMinifier.cs')
    }
    $source = [IO.File]::ReadAllText($SourcePath)
    $blocks = @{}
    foreach ($name in @('WindhawkMod', 'WindhawkModReadme', 'WindhawkModSettings')) {
        $pattern = '(?ms)^// ==' + $name + '==\r?\n.*?^// ==/' + $name + '==[^\S\r\n]*(?:\r?\n|$)'
        $matches = [regex]::Matches($source, $pattern)
        if ($matches.Count -ne 1) { throw "Expected one $name block in $SourcePath" }
        $blocks[$name] = $matches[0].Value.TrimEnd([char]13, [char]10)
        $source = [regex]::Replace($source, $pattern, '')
    }
    # These comments are Windhawk's input format, not removable C++ commentary.
    return $blocks['WindhawkMod'] + "`n" +
        "// ==WindhawkModReadme==`n/*`nGenerated by build.bat from the numbered source. Read-only; edits are discarded on rebuild.`n*/`n// ==/WindhawkModReadme==`n" +
        $blocks['WindhawkModSettings'] + "`n" + [WindhawkSourceMinifier]::Minify($source)
}
